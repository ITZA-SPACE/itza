// Writes src/copy/generated/keys.ts: the union of every key in src/copy/en/*.json, so `t(key)` is typed
// without a shared list. Run by `pnpm gen` and by the Vite plugin in dev and build.
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const copyDir = join(root, "src/copy/en");
const target = join(root, "src/copy/generated/keys.ts");

export function writeCopyKeys() {
  const owners = new Map();
  for (const file of readdirSync(copyDir)
    .filter((f) => f.endsWith(".json"))
    .sort()) {
    for (const key of Object.keys(JSON.parse(readFileSync(join(copyDir, file), "utf8")))) {
      if (owners.has(key))
        throw new Error(`Copy key "${key}" is in both ${owners.get(key)} and ${file}`);
      owners.set(key, file);
    }
  }
  const keys = [...owners.keys()].sort();
  const body = [
    "// Generated by scripts/copyKeys.mjs from src/copy/en/*.json. Do not edit; not committed.",
    `export type CopyKey =\n${keys.map((k) => `  | ${JSON.stringify(k)}`).join("\n")};`,
    "",
  ].join("\n");
  mkdirSync(dirname(target), { recursive: true });
  let current = "";
  try {
    current = readFileSync(target, "utf8");
  } catch {}
  if (current !== body) writeFileSync(target, body);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) writeCopyKeys();
