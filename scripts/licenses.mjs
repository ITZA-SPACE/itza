#!/usr/bin/env node
// Dependency license register: lists every shipped JavaScript and Python dependency with its
// license into the generated block of THIRD_PARTY_NOTICES.md, and fails on any license that is
// not OSI-approved or public domain unless the package is in scripts/licenses.allow.json.
//
//   node scripts/licenses.mjs                 regenerate the block (needs `pnpm install` and `uv sync`)
//   node scripts/licenses.mjs --check         fail on a disallowed license or a stale block
//   node scripts/licenses.mjs --fixture <dir> read <dir>/pnpm.json and <dir>/python.json instead of
//                                             the real lockfile installs; never touches the notices
//
// JavaScript: `pnpm -r licenses list --prod` (every workspace, production dependencies only).
// Python: the installed `.dist-info` metadata of each uv project, read from its `.venv`
// (`uv sync` installs from uv.lock). Dev-only JavaScript tooling is not shipped and is not listed.
import { spawnSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const NOTICES = join(ROOT, "THIRD_PARTY_NOTICES.md");
const ALLOW = join(ROOT, "scripts/licenses.allow.json");
const BEGIN = "<!-- licenses:begin (generated by scripts/licenses.mjs; do not edit) -->";
const END = "<!-- licenses:end -->";
// Every uv project in the repository (each has its own uv.lock).
const PYTHON_PROJECTS = ["services/science-api", "pipelines", "pipelines/ml"];
// Workspace packages of this repository, not third-party.
const OWN_PYTHON = new Set(["itza-science", "itza-demo-pipeline", "itza-ml"]);

// SPDX ids of OSI-approved licenses and public-domain dedications that appear in dependency trees.
const ACCEPTED = new Set(
  [
    "0BSD",
    "AFL-2.1",
    "Apache-2.0",
    "BlueOak-1.0.0",
    "BSD-1-Clause",
    "BSD-2-Clause",
    "BSD-3-Clause",
    "BSL-1.0",
    "CC0-1.0",
    "ISC",
    "LGPL-2.1-only",
    "LGPL-2.1-or-later",
    "LGPL-3.0-only",
    "LGPL-3.0-or-later",
    "MIT",
    "MIT-0",
    "MPL-2.0",
    "PSF-2.0",
    "Python-2.0",
    "Unlicense",
    "Zlib",
  ].map((id) => id.toLowerCase()),
);

/** True when an SPDX expression is acceptable: OR needs one accepted side, AND needs every side. */
export function acceptable(expression) {
  // Taken from an "OSI Approved" trove classifier (see pythonLicense).
  if (expression.endsWith(" (OSI)")) return true;
  const tokens = expression.replace(/[()]/g, " ").trim().split(/\s+/);
  const groups = [[]];
  for (const token of tokens) {
    if (token.toUpperCase() === "OR") groups.push([]);
    else if (token.toUpperCase() !== "AND") groups.at(-1).push(token);
  }
  return groups.some((all) => all.length > 0 && all.every((id) => ACCEPTED.has(id.toLowerCase())));
}

/** The license of one Python distribution, as an SPDX expression or "UNKNOWN". */
export function pythonLicense(metadata) {
  const expression = /^License-Expression: (.+)$/m.exec(metadata)?.[1]?.trim();
  if (expression) return expression;
  // Older metadata: the trove classifiers name the license family, the License field is free text.
  const field = /^License: (.+)$/m.exec(metadata)?.[1]?.trim() ?? "";
  if (/^[A-Za-z0-9.+-]+( (AND|OR) [A-Za-z0-9.+-]+)*$/.test(field) && acceptable(field))
    return field;
  const classifiers = [...metadata.matchAll(/^Classifier: License :: OSI Approved :: (.+)$/gm)];
  if (classifiers.length) return classifiers.map((m) => m[1].trim()).join(" AND ") + " (OSI)";
  return "UNKNOWN";
}

/** Problems with the source manifest: every entry needs a license and a citation; DAAC products a DOI. */
export function manifestProblems(yamlText) {
  const problems = [];
  for (const block of yamlText.split(/^ {2}- id: /m).slice(1)) {
    const id = block.split("\n")[0].trim();
    for (const key of ["license", "citation"]) {
      if (!new RegExp(`^ {4}${key}: \\S`, "m").test(block))
        problems.push(`data-sources.yaml: ${id} has no ${key}`);
    }
    const daac = /^ {4}provider: .*(DAAC|GES DISC)/m.test(block);
    if (daac && !/^ {4}doi: \S/m.test(block)) problems.push(`data-sources.yaml: ${id} has no doi`);
  }
  return problems;
}

function jsDependencies() {
  const run = spawnSync("pnpm", ["-r", "licenses", "list", "--prod", "--json"], {
    cwd: ROOT,
    encoding: "utf8",
    maxBuffer: 1 << 28,
  });
  if (run.status !== 0) throw new Error(`pnpm licenses failed: ${run.stderr || run.stdout}`);
  return parsePnpm(run.stdout);
}

export function parsePnpm(json) {
  const out = [];
  for (const [license, packages] of Object.entries(JSON.parse(json))) {
    for (const p of packages) {
      for (const version of p.versions) out.push({ name: p.name, version, license, source: "js" });
    }
  }
  return out;
}

function pythonDependencies() {
  const out = [];
  for (const project of PYTHON_PROJECTS) {
    const lib = join(ROOT, project, ".venv/lib");
    if (!existsSync(lib))
      throw new Error(`${project}/.venv is missing: run \`uv sync\` there first`);
    for (const python of readdirSync(lib)) {
      const site = join(lib, python, "site-packages");
      if (!existsSync(site)) continue;
      for (const entry of readdirSync(site).filter((e) => e.endsWith(".dist-info"))) {
        const metadata = readFileSync(join(site, entry, "METADATA"), "utf8");
        const name = /^Name: (.+)$/m.exec(metadata)?.[1]?.trim();
        const version = /^Version: (.+)$/m.exec(metadata)?.[1]?.trim();
        if (name && version && !OWN_PYTHON.has(name)) {
          out.push({ name, version, license: pythonLicense(metadata), source: "python" });
        }
      }
    }
  }
  return out;
}

function dedupe(list) {
  const seen = new Map();
  for (const d of list) seen.set(`${d.source}:${d.name.toLowerCase()}@${d.version}`, d);
  return [...seen.values()].sort(
    (a, b) =>
      a.source.localeCompare(b.source) || a.name.toLowerCase().localeCompare(b.name.toLowerCase()),
  );
}

function render(deps) {
  const section = (title, source) => {
    const rows = deps.filter((d) => d.source === source);
    const lines = rows.map((d) => `| ${d.name} | ${d.version} | ${d.license} |`);
    return [
      `### ${title} (${rows.length})`,
      "",
      "| Package | Version | License |",
      "|---|---|---|",
      ...lines,
    ];
  };
  return [
    BEGIN,
    "",
    ...section("JavaScript packages (production dependencies of every workspace)", "js"),
    "",
    ...section("Python packages (every uv project, as locked in uv.lock)", "python"),
    "",
    END,
  ].join("\n");
}

function main() {
  const args = process.argv.slice(2);
  const check = args.includes("--check");
  const fixture = args.includes("--fixture") ? resolve(args[args.indexOf("--fixture") + 1]) : null;
  const allow = existsSync(ALLOW) ? JSON.parse(readFileSync(ALLOW, "utf8")) : {};

  const deps = dedupe(
    fixture
      ? [
          ...parsePnpm(readFileSync(join(fixture, "pnpm.json"), "utf8")),
          ...JSON.parse(readFileSync(join(fixture, "python.json"), "utf8")).map((d) => ({
            ...d,
            source: "python",
          })),
        ]
      : [...jsDependencies(), ...pythonDependencies()],
  );

  const manifest = fixture
    ? []
    : manifestProblems(readFileSync(join(ROOT, "data-sources.yaml"), "utf8"));
  for (const problem of manifest) console.error(problem);
  if (manifest.length) process.exit(1);

  const bad = deps.filter((d) => !acceptable(d.license) && !(d.name in allow));
  for (const d of bad) {
    console.error(`license not allowed: ${d.source} ${d.name}@${d.version} (${d.license})`);
  }
  if (bad.length) {
    console.error(
      `${bad.length} dependency license(s) are neither OSI-approved nor public domain.`,
    );
    console.error("Replace the package, or add it to scripts/licenses.allow.json with a reason.");
    process.exit(1);
  }
  if (fixture) return console.log(`${deps.length} dependencies, all licenses accepted`);

  const current = readFileSync(NOTICES, "utf8");
  const start = current.indexOf(BEGIN);
  const end = current.indexOf(END);
  if (start < 0 || end < 0)
    throw new Error("THIRD_PARTY_NOTICES.md lacks the licenses:begin/end markers");
  const next = current.slice(0, start) + render(deps) + current.slice(end + END.length);
  if (check) {
    if (next !== current) {
      console.error("THIRD_PARTY_NOTICES.md is out of date: run `node scripts/licenses.mjs`.");
      process.exit(1);
    }
    return console.log(`${deps.length} dependencies, all licenses accepted, notices current`);
  }
  writeFileSync(NOTICES, next);
  console.log(`THIRD_PARTY_NOTICES.md updated: ${deps.length} dependencies`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
